// Single source for the GDS message map: built-in vocabulary per locale, with
// the Arabic overlay applied on top of the English base.
export function getAppGdsMessages(locale: string): Record<string, string> {
  const base = getGdsMessages(locale);
  if (locale === "ar") {
    return { ...base, ...ARABIC_GDS_MESSAGES };
  }
  return base;
}
